export function particle(name, vowel, consonant) {
  const syllable = name.charCodeAt(name.length-1)-0xac00;
  return name+(syllable%28===0?vowel:consonant);
}

export function biography({pick,region,origin,job,start,turning,age,relationships}) {
  const [family,teacher,colleague] = relationships;
  const relativeBare = family.role+' '+family.name;
  const mentor = teacher.name;
  const friendBare = colleague.role+' '+colleague.name;
  const fields = {
    origin,job,start,turning,relativeBare,mentor,friendBare,
    relative:particle(relativeBare,'와','과'),
    relativeSubject:particle(relativeBare,'가','이'),
    relativeObject:particle(relativeBare,'를','을'),
    mentorTopic:particle(mentor,'는','은'),
    mentorSubject:particle(mentor,'가','이'),
    mentorWith:particle(mentor,'와','과'),
    friend:particle(friendBare,'와','과'),friendSubject:particle(friendBare,'가','이')
  };
  const fill = text => text.replace(/\{(\w+)\}/g, (_,key)=>fields[key]);
  const [memory,memoryAxis,memorySecondary] = pick([...childhoods[region],...sharedChildhoods]);
  const [lesson,lessonAxis,lessonSecondary,lessonContinued] = pick(apprenticeships);
  const incidentPool = pick([regionalIncidents[region],regionalIncidents[region],sharedIncidents]);
  const [situation,responses] = pick(incidentPool);
  const [response,responseAxis,responseSecondary] = pick(responses);
  const [legacy,legacyAxis,legacySecondary] = pick(pick([regionalLegacies[region],legacies]));
  const firstJob = pick([
    '{start}세부터 {job} 일을 맡았다.',
    '{job} 일을 처음 맡은 건 {start}세였다.',
    '{start}세에 {job} 일을 시작하면서 하루의 순서가 달라졌다.'
  ]);
  const turningPoint = pick([
    '{turning}세에 일이 달라졌다. '+situation+' '+response,
    situation+' 그 일을 겪었을 때는 {turning}세였다. '+response,
    '{turning}세 무렵 '+situation+' '+response
  ]);
  const event = (text,from,to,focus,rate,secondary=[]) => ({
    text:fill(text),from,to,rate,
    weights:Array.from({length:6},(_,axis)=>axis===focus?1:secondary.includes(axis)?.4:0)
  });
  return [
    event(pick(openings)+' '+memory,6,start,memoryAxis,.32,memorySecondary),
    event(firstJob+' '+lesson,start,lessonContinued?turning:start+3,lessonAxis,.75,lessonSecondary),
    event(turningPoint,turning,turning+1,responseAxis,1.3,responseSecondary),
    event(legacy,age-9,age,legacyAxis,.48,legacySecondary)
  ];
}
